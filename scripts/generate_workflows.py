#!/usr/bin/env python3
"""Generate one GitHub Actions workflow per channel (+ the rotation workflow).

Reads config.json + watch_list.json and writes:

  .github/workflows/ch-<id>-<slug>.yml      one dedicated workflow per channel
  .github/workflows/_matrix-rotation.yml    N channels per slot, rotating
  .github/workflows.disabled/               frozen copies in portal-only mode

Modes (config.json -> mode):

  selfhosted    cron + self-hosted runner labels, all channels stream 24/7
  github-hosted ONE ACTIVE 24/7 workflow per channel on ubuntu-latest (cron +
               manual + repository_dispatch + a per-channel push kick). Free
               and unlimited for public repos, but capped at 20 concurrent jobs.
  github-free   dispatch-only per-channel workflows, cron on the rotation job
               (fits inside the 2,000 min/month free budget)
  portal-only  no active streaming workflows at all - near-zero minutes,
               the catalog/playlists/portal still refresh every 6 hours

Re-run after every catalog change:  python3 scripts/generate_workflows.py
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import (  # noqa: E402
    ROOT,
    load_config,
    load_watch_list,
    slugify,
)

WORKFLOWS = ROOT / ".github" / "workflows"
DISABLED = ROOT / ".github" / "workflows.disabled"
MARKER = "GENERATED FILE - DO NOT EDIT"

CHANNEL_TEMPLATE = """# ==============================================================================
# {marker}
# Generated by scripts/generate_workflows.py from watch_list.json.
# channel : {cid} - {name} ({group}) - panel status: {panel_status}
# mode    : {mode}
# Re-generate: python3 scripts/generate_workflows.py
# ==============================================================================
name: ch-{cid}-{slug}

on:
{triggers}
concurrency:
  group: ch-{cid}
  cancel-in-progress: false

permissions:
  contents: write

jobs:
  restream:
    runs-on: {runs_on}
    timeout-minutes: {job_timeout}
    # a repository_dispatch may target a single channel
    if: >-
      github.event_name != 'repository_dispatch' ||
      github.event.client_payload.channel == '' ||
      github.event.client_payload.channel == '{cid}' ||
      github.event.client_payload.channel == null
    steps:
      - name: Checkout
        uses: actions/checkout@v4

      - name: Refresh panel token
        continue-on-error: true
        run: |
          python3 scripts/refresh_token.py --out watch_list.json || \
            echo "::warning::token refresh failed - the loop will retry every 30s"

      - name: Channel availability
        id: availability
        run: |
          python3 - <<'PY'
          import json, os
          data = json.load(open("watch_list.json"))
          ch = next((c for c in data.get("channels", []) if c["id"] == "{cid}"), None)
          online = bool(ch and ch.get("online"))
          print(f"panel_online={{online}}")
          with open(os.environ["GITHUB_OUTPUT"], "a") as fh:
              fh.write(f"online={{str(online).lower()}}\\n")
          PY

      - name: Restream {cid} ({name})
        if: steps.availability.outputs.online == 'true'
        env:
          CHANNEL_ID: "{cid}"
          STAGGER_SECONDS: "{stagger}"
        run: |
          timeout {loop_timeout} bash scripts/restart_loop.sh "{cid}" "$TOKEN" || true

      - name: Heartbeat
        if: always()
        continue-on-error: true
        run: bash scripts/heartbeat.sh "{cid}" "finished"

      - name: Commit heartbeat
        if: always()
        continue-on-error: true
        env:
          CI_COMMIT_PATHS: ".state"
        run: bash scripts/ci_commit.sh "chore(beat): {cid}"
"""

TRIGGER_SCHEDULE = """  schedule:
    - cron: "{cron}"
  workflow_dispatch:
  repository_dispatch:
    types: [restart-channel]
"""

TRIGGER_SCHEDULE_KICK = """  schedule:
    - cron: "{cron}"
  workflow_dispatch:
  repository_dispatch:
    types: [restart-channel]
  push:
    paths:
      - "data/trigger/{cid}"
"""

TRIGGER_MANUAL = """  workflow_dispatch:
  repository_dispatch:
    types: [restart-channel]
"""

ROTATION_TEMPLATE = """# ==============================================================================
# {marker}
# Rotating matrix restream: streams a slice of the catalog per slot and walks
# through every channel across the day. Best fit for the 2,000 min/month
# free-tier budget.
# Generated by scripts/generate_workflows.py
# ==============================================================================
name: _matrix-rotation

on:
{triggers}
concurrency:
  group: matrix-rotation
  cancel-in-progress: false

permissions:
  contents: write

jobs:
  plan:
    runs-on: ubuntu-latest
    outputs:
      channels: ${{{{ steps.plan.outputs.channels }}}}
      slot: ${{{{ steps.plan.outputs.slot }}}}
    steps:
      - uses: actions/checkout@v4
      - name: Refresh catalog
        run: python3 scripts/refresh_token.py --out watch_list.json
      - name: Pick this slot's channels
        id: plan
        run: python3 scripts/rotation_plan.py --per-slot {per_slot} --slots {slots}

  stream:
    needs: plan
    if: needs.plan.outputs.channels != '[]'
    strategy:
      fail-fast: false
      max-parallel: {max_parallel}
      matrix:
        channel: ${{{{ fromJson(needs.plan.outputs.channels) }}}}
    runs-on: {runs_on}
    timeout-minutes: {job_timeout}
    steps:
      - uses: actions/checkout@v4
      - name: Refresh panel token
        run: python3 scripts/refresh_token.py --out watch_list.json
      - name: Restream ${{{{ matrix.channel.name }}}}
        run: |
          timeout {loop_timeout} bash scripts/restart_loop.sh "${{{{ matrix.channel.id }}}}" "$TOKEN" || true
"""

DISABLED_NOTE = """# Disabled restream workflows

`config.json -> mode` is currently **portal-only**, so no streaming job runs and
no GitHub Actions minutes are spent on video.

These are the fully generated per-channel workflows. To turn streaming on:

1. Edit `config.json`:
   * `"dest_mode": "rtmp"` + `rtmp.url` (nginx-rtmp / MediaMTX / any RTMP ingest), or
   * `"dest_mode": "hls-rehost"` (segments written per job), or
   * `"dest_mode": "proxy-only"` (cloud relay only, no ffmpeg fan-out).
2. Set `"mode"` to `"selfhosted"` (all channels, self-hosted runner) or
   `"github-free"` (rotation matrix inside the free minute budget).
3. Run `python3 scripts/generate_workflows.py` and commit the result.

The generator moves files between `.github/workflows/` (active) and
`.github/workflows.disabled/` (inert) automatically.
"""


def yaml_comment(text: str) -> str:
    return " ".join(str(text or "").replace("\r", " ").replace("\n", " ").split())


def build_channel_workflow(cfg: dict, channel: dict, mode: str, index: int) -> tuple[str, bool]:
    restream = cfg.get("restream", {}) or {}
    schedule = cfg.get("schedule", {}) or {}
    slug = slugify(channel["name"], 28)
    cron = schedule.get("token_cron", "17 */6 * * *")

    if mode == "selfhosted":
        runs_on = "[" + ", ".join(cfg.get("selfhosted", {}).get("runner_labels", ["self-hosted", "linux"])) + "]"
        triggers = TRIGGER_SCHEDULE.format(cron=cron)
        scheduled = True
    elif mode == "github-hosted":
        runs_on = "ubuntu-latest"
        # every channel gets its own minute so 170 cron jobs never pile up
        minute = (int(schedule.get("cron_minutes", [17])[0]) + index * 7) % 60
        triggers = TRIGGER_SCHEDULE_KICK.format(cron=f"{minute} */6 * * *", cid=channel["id"])
        scheduled = True
    elif mode == "github-free":
        runs_on = "ubuntu-latest"
        triggers = TRIGGER_MANUAL
        scheduled = False
    else:
        runs_on = "ubuntu-latest"
        triggers = TRIGGER_MANUAL
        scheduled = False

    body = CHANNEL_TEMPLATE.format(
        marker=MARKER,
        cid=channel["id"],
        name=yaml_comment(channel["name"]),
        group=yaml_comment(channel.get("group", "")),
        panel_status="online" if channel.get("online") else "offline",
        slug=slug,
        mode=mode,
        triggers=triggers,
        runs_on=runs_on,
        job_timeout=int(restream.get("job_timeout_minutes", 355)),
        stagger=int(restream.get("stagger_seconds", 10)) * (index % 30),
        loop_timeout=int(restream.get("loop_timeout_seconds", 21000)),
    )
    return body, scheduled


def build_rotation_workflow(cfg: dict, mode: str) -> str:
    schedule = cfg.get("schedule", {}) or {}
    restream = cfg.get("restream", {}) or {}
    free = cfg.get("github_free", {}) or {}

    cron_active = mode in ("github-free", "selfhosted", "github-hosted")
    triggers = (
        f'  schedule:\n    - cron: "{schedule.get("rotation_cron", "7 */6 * * *")}"\n'
        "  workflow_dispatch:\n"
        "  repository_dispatch:\n    types: [rotate]\n"
        if cron_active
        else "  workflow_dispatch:\n  repository_dispatch:\n    types: [rotate]\n"
    )
    runs_on = (
        "[" + ", ".join(cfg.get("selfhosted", {}).get("runner_labels", ["self-hosted", "linux"])) + "]"
        if mode == "selfhosted"
        else "ubuntu-latest"
    )
    return ROTATION_TEMPLATE.format(
        marker=MARKER,
        triggers=triggers,
        per_slot=int(free.get("channels_per_slot", 2)),
        slots=int(schedule.get("rotation_slots", 6)),
        max_parallel=int(restream.get("max_parallel", 3)),
        runs_on=runs_on,
        job_timeout=int(restream.get("job_timeout_minutes", 355)),
        loop_timeout=int(restream.get("loop_timeout_seconds", 21000)),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=None)
    parser.add_argument("--watch-list", default=None)
    parser.add_argument("--mode", default=None, help="override config.json mode")
    parser.add_argument("--clean", action="store_true", help="drop workflows for removed channels")
    parser.add_argument("--workflows-dir", default=None, help="override .github/workflows (tests)")
    parser.add_argument("--disabled-dir", default=None, help="override .github/workflows.disabled (tests)")
    args = parser.parse_args()

    cfg = load_config(args.config)
    mode = (args.mode or cfg.get("mode") or "portal-only").lower()
    if mode not in ("selfhosted", "github-hosted", "github-free", "portal-only"):
        print(f"::error::unknown mode '{mode}' (expected selfhosted | github-hosted | github-free | portal-only)")
        return 2

    watch = load_watch_list()
    channels = watch.get("channels") or []
    if not channels:
        print("::error::watch_list.json has no channels - run scripts/bootstrap_catalog.py or refresh_token.py")
        return 1

    global WORKFLOWS, DISABLED
    if args.workflows_dir:
        WORKFLOWS = Path(args.workflows_dir)
    if args.disabled_dir:
        DISABLED = Path(args.disabled_dir)
    target = WORKFLOWS if mode != "portal-only" else DISABLED
    other = DISABLED if mode != "portal-only" else WORKFLOWS
    target.mkdir(parents=True, exist_ok=True)
    other.mkdir(parents=True, exist_ok=True)

    written = 0
    scheduled = 0
    generated_names: set[str] = set()
    for index, channel in enumerate(channels):
        body, has_cron = build_channel_workflow(cfg, channel, mode, index)
        name = f"ch-{channel['id']}-{slugify(channel['name'], 28)}.yml"
        generated_names.add(name)
        (target / name).write_text(body, encoding="utf-8")
        # never leave a stale copy in the other directory
        stale = other / name
        if stale.exists():
            stale.unlink()
        written += 1
        scheduled += 1 if has_cron else 0

    rotation = build_rotation_workflow(cfg, mode)
    rotation_dir = WORKFLOWS if mode != "portal-only" else DISABLED
    rotation_dir.mkdir(parents=True, exist_ok=True)
    (rotation_dir / "_matrix-rotation.yml").write_text(rotation, encoding="utf-8")
    other_rotation = (DISABLED if rotation_dir == WORKFLOWS else WORKFLOWS) / "_matrix-rotation.yml"
    if other_rotation.exists():
        other_rotation.unlink()

    if args.clean:
        for folder in (WORKFLOWS, DISABLED):
            for path in folder.glob("ch-*.yml"):
                if path.name not in generated_names:
                    path.unlink()
                    print(f"removed stale {path.relative_to(ROOT)}")

    if mode == "portal-only":
        (DISABLED / "README.md").write_text(DISABLED_NOTE, encoding="utf-8")
    else:
        stale_note = DISABLED / "README.md"
        if stale_note.exists():
            stale_note.unlink()

    save_manifest = {
        "generated_at": __import__("common").now_iso(),
        "mode": mode,
        "dest_mode": cfg.get("dest_mode"),
        "active_directory": str(target.relative_to(ROOT)) if mode != "portal-only" else ".github/workflows.disabled",
        "channels": len(channels),
        "scheduled_workflows": scheduled,
        "rotation": "_matrix-rotation.yml",
    }
    save_manifest_path = ROOT / ".github" / "workflows-manifest.json"
    save_manifest_path.parent.mkdir(parents=True, exist_ok=True)
    save_manifest_path.write_text(json.dumps(save_manifest, indent=2) + "\n", encoding="utf-8")

    print(f"mode={mode}: wrote {written} channel workflows + rotation to "
          f"{(target.relative_to(ROOT))} ({scheduled} with cron)")
    if mode == "portal-only":
        print("portal-only: streaming workflows are inert in .github/workflows.disabled/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
