/* EasyISP24 Restream - portal behaviour
   Generated by scripts/build_site.py - edit templates/site.js */
(function () {
  "use strict";

  var cfgEl = document.getElementById("site-config");
  var CONFIG = cfgEl ? JSON.parse(cfgEl.textContent) : {};
  var CHANNELS = CONFIG.channels || [];
  var LS_KEY = "easyisp24.proxy";

  function storedProxy() {
    try { return localStorage.getItem(LS_KEY) || ""; } catch (e) { return ""; }
  }

  function proxyBase() {
    return (storedProxy() || CONFIG.proxy || "").replace(/\/+$/, "");
  }

  function streamUrl(channel) {
    var base = proxyBase();
    if (base) return base + "/live/" + channel.id + ".m3u8";
    return channel.stream_url;
  }

  window.EasyISP = { streamUrl: streamUrl, proxyBase: proxyBase };

  function toast(message) {
    var el = document.getElementById("toast");
    if (!el) {
      el = document.createElement("div");
      el.id = "toast";
      el.className = "toast";
      document.body.appendChild(el);
    }
    el.textContent = message;
    el.classList.add("show");
    clearTimeout(el._t);
    el._t = setTimeout(function () { el.classList.remove("show"); }, 1900);
  }
  window.EasyToast = toast;

  function copy(text) {
    if (navigator.clipboard && window.isSecureContext) {
      navigator.clipboard.writeText(text).then(function () { toast("Link copied"); },
        function () { fallbackCopy(text); });
    } else {
      fallbackCopy(text);
    }
  }

  function fallbackCopy(text) {
    var ta = document.createElement("textarea");
    ta.value = text;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand("copy"); toast("Link copied"); }
    catch (e) { toast("Copy failed - select the link manually"); }
    document.body.removeChild(ta);
  }

  document.addEventListener("click", function (event) {
    var target = event.target.closest("[data-copy]");
    if (!target) return;
    event.preventDefault();
    var value = target.getAttribute("data-copy");
    if (value === "stream") {
      var id = target.getAttribute("data-id");
      var channel = CHANNELS.filter(function (c) { return c.id === id; })[0];
      if (channel) value = new URL(streamUrl(channel), location.href).href;
    }
    if (value) copy(value);
  });

  /* animate stat counters -------------------------------------------------- */
  document.querySelectorAll("[data-count]").forEach(function (el) {
    var end = parseInt(el.getAttribute("data-count"), 10) || 0;
    if (end === 0) { el.textContent = "0"; return; }
    var start = 0;
    var duration = 900;
    var t0 = performance.now();
    function step(now) {
      var p = Math.min(1, (now - t0) / duration);
      var eased = 1 - Math.pow(1 - p, 3);
      el.textContent = Math.round(start + (end - start) * eased).toLocaleString();
      if (p < 1) requestAnimationFrame(step);
    }
    requestAnimationFrame(step);
  });

  /* dashboard filtering ---------------------------------------------------- */
  var grid = document.getElementById("channel-grid");
  if (!grid) return;

  var searchInput = document.getElementById("q");
  var groupSelectc = document.getElementById("group");
  var stateChips = Array.prototype.slice.call(document.querySelectorAll("[data-filter-state]"));
  var countLabel = document.getElementById("visible-count");
  var emptyState = document.getElementById("empty-state");
  var activeState = "all";

  function matchState(channel, state) {
    if (state === "all") return true;
    if (state === "live") return channel.state === "ok";
    if (state === "offline") return channel.state !== "ok";
    if (state === "panel") return !!channel.online;
    return true;
  }

  function apply() {
    var q = (searchInput && searchInput.value || "").trim().toLowerCase();
    var group = groupSelectc && groupSelectc.value || "";
    var visible = 0;

    Array.prototype.forEach.call(grid.children, function (card) {
      if (!card.dataset || !card.dataset.id) return;
      var ch = CHANNELS.filter(function (c) { return c.id === card.dataset.id; })[0];
      if (!ch) return;
      var ok = matchState(ch, activeState);
      if (ok && group && ch.group !== group) ok = false;
      if (ok && q) {
        ok = (ch.name + " " + ch.id + " " + ch.group).toLowerCase().indexOf(q) !== -1;
      }
      card.style.display = ok ? "" : "none";
      if (ok) visible++;
    });

    if (countLabel) countLabel.textContent = String(visible);
    if (emptyState) emptyState.style.display = visible === 0 ? "" : "none";
  }

  if (searchInput) searchInput.addEventListener("input", apply);
  if (groupSelectc) groupSelectc.addEventListener("change", apply);
  stateChips.forEach(function (chip) {
    chip.addEventListener("click", function () {
      activeState = chip.getAttribute("data-filter-state");
      stateChips.forEach(function (other) {
        other.setAttribute("aria-pressed", other === chip ? "true" : "false");
      });
      apply();
    });
  });

  /* proxy override -------------------------------------------------------- */
  var proxyInput = document.getElementById("proxy-base");
  if (proxyInput) {
    proxyInput.value = storedProxy() || CONFIG.proxy || "";
    var save = function () {
      try { localStorage.setItem(LS_KEY, proxyInput.value.trim()); } catch (e) {}
      location.reload();
    };
    proxyInput.addEventListener("change", save);
    var clearBtn = document.getElementById("proxy-clear");
    if (clearBtn) clearBtn.addEventListener("click", function () {
      try { localStorage.removeItem(LS_KEY); } catch (e) {}
      location.reload();
    });
  }

  apply();
})();
